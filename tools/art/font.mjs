export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in image pixels of `text` drawn at `size` pixels per font pixel. */
export function textWidth(text, size) {
  return text.length * (GLYPH_W + 1) * size - size;
}

/**
 * Draw `text` with its top left at (x, y), `size` image pixels per font pixel. Letters are drawn as
 * capitals; a lower-case `x` stays as the times sign. Unknown characters are left blank.
 */
export function drawText(img, x, y, text, colour, size = 1) {
  let cx = x;
  for (const ch of text) {
    const g = GLYPHS[ch === 'x' ? 'x' : ch.toUpperCase()] ?? GLYPHS[' '];
    for (let row = 0; row < GLYPH_H; row++)
      for (let col = 0; col < GLYPH_W; col++)
        if (g[row][col] === '1')
          for (let dy = 0; dy < size; dy++) for (let dx = 0; dx < size; dx++) put(img, cx + col * size + dx, y + row * size + dy, colour);
    cx += (GLYPH_W + 1) * size;
  }
}
